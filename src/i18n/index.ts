const DICTS: Record<string, Messages> = { en, es, fr, de, ja, ko, zh };

let current = 'en';

export function setLocale(locale: string | null | undefined): void {
  if (locale && DICTS[locale]) current = locale;
}

export function activeLocale(): string {
  return current;
}

export function tr(key: string): string {
  return DICTS[current]?.[key] ?? en[key] ?? key;
}

