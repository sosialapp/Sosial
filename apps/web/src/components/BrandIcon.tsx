/**
 * Optical padding — edge-touching brand paths lose antialiased pixels at
 * the svg viewport and read as "cut", worst at small sizes. A 2-unit inset
 * stops the clip everywhere the mark renders.
 */
function Pad({ children }: { children: ReactNode }) {
  return <g transform="translate(2 2) scale(0.8333)">{children}</g>;
}

/** Path data for places that need to compose a custom SVG (e.g. a gradient). */
export const BRAND_PATHS = PATHS;

/**
 * Per-provider path transforms centering non-24-box art inside the 24×24
 * box. Everything else fills 24×24 natively and needs no transform.
 */
export const GLYPH_TRANSFORMS: Partial<Record<BrandProvider, string>> = {
  vk: 'scale(1.2)',
};

/** Icon-context glyph: plane-only for Telegram (official app-icon style). */
function iconPath(provider: BrandProvider): string {
  return provider === 'telegram' ? planeFromBundledMark(PATHS.telegram) : PATHS[provider];
}

/**
 * The plane fills ~70% of its viewBox where other marks fill edge to edge —
 * without this it renders small everywhere. 1.3x about the center still
 * clears the viewport after Pad insets it.
 */
const TELEGRAM_SCALE = 'translate(12 12) scale(1.5) translate(-12 -12)';

function Glyph({ provider }: { provider: BrandProvider }) {
  if (provider === 'telegram') {
    return (
      <g transform={TELEGRAM_SCALE}>
        <path d={iconPath(provider)} />
      </g>
    );
  }
  const t = GLYPH_TRANSFORMS[provider];
  if (t) {
    return (
      <g transform={t}>
        <path d={PATHS[provider]} />
      </g>
    );
  }
  return <path d={PATHS[provider]} />;
}
